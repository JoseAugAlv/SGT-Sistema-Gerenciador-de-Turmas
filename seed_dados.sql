-- =====================================================================
-- 8. GRUPO_ALUNOS (round-robin: cada aluno entra em 1 dos 5 grupos)
-- =====================================================================
INSERT INTO grupo_alunos (grupo_id, usuario_id)
SELECT g.id, r.aluno_id
FROM (
  SELECT sa.id AS aluno_id, sa.turma_id,
    (SELECT COUNT(*) FROM _seed_alunos s2 WHERE s2.turma_id = sa.turma_id AND s2.id <= sa.id) AS rn
  FROM _seed_alunos sa
) r
JOIN projetos p ON p.turma_id = r.turma_id
JOIN grupos g ON g.projeto_id = p.id
WHERE g.nome = CONCAT('Grupo ', LPAD(MOD(r.rn - 1, 5) + 1, 2, '0'));

-- =====================================================================
-- 9. GRUPO_DIRETORES (1 diretor por grupo: o primeiro aluno do grupo)
-- =====================================================================
INSERT INTO grupo_diretores (grupo_id, usuario_id, ativo, nomeado_por, nomeado_em)
SELECT g.id, (SELECT MIN(ga.usuario_id) FROM grupo_alunos ga WHERE ga.grupo_id = g.id), 1, 1, NOW()
FROM grupos g
WHERE g.projeto_id >= 100
  AND EXISTS (SELECT 1 FROM grupo_alunos ga WHERE ga.grupo_id = g.id);

